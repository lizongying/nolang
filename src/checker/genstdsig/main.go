// Command genstdsig generates src/checker/stdsig_gen.go, which bakes the std
// module signature tables into the `no` binary as Go source literals. This
// lets `no build` skip the PASS1 signature collection on every build,
// including the cold (first) build, without a separate //go:embed blob.
//
// It reads the on-disk src/std tree (the same files //go:embed compiles into
// StdFS), reuses the exact collection logic from the checker package, and
// emits the four maps plus the std-content key used at runtime to detect a
// stale table.
//
// Run via `go generate ./checker/` (cwd = src/checker) or `make gen`.
package main

import (
	"bytes"
	"compress/gzip"
	"encoding/gob"
	"flag"
	"fmt"
	goformat "go/format"
	"os"
	"path/filepath"
	"runtime"
	"sort"
	"strconv"

	"github.com/lizongying/nolang/checker"
)

const header = "// Code generated by genstdsig. DO NOT EDIT.\n" +
	"// Bakes the std module signature tables into the no binary as Go source\n" +
	"// literals so no build skips PASS1 signature collection on every build\n" +
	"// (including cold). Regenerate via 'go generate ./checker/' (or 'make gen')\n" +
	"// after editing src/std.\n\n" +
	"package checker\n\n"

func main() {
	keyOnly := flag.Bool("key-only", false, "only compute and print the std signature key, then exit (used by the Makefile to inject it via -X)")
	flag.Parse()

	_, thisFile, _, ok := runtime.Caller(0)
	if !ok {
		fatal("genstdsig: cannot determine own source path")
	}
	genDir := filepath.Dir(thisFile) // .../src/checker/genstdsig
	repoRoot := filepath.Clean(filepath.Join(genDir, "..", "..", ".."))
	srcDir := filepath.Join(repoRoot, "src")
	fsys := os.DirFS(srcDir)

	// Independent std-signature key computation. This hashes the CURRENT
	// on-disk src/std tree from scratch — it does NOT read the key baked into
	// stdsig_gen.go. The Makefile captures this output and injects it into the
	// binary via -X (checker.StdSigKey). At runtime the injected key is
	// compared against embeddedStdSigKey (which genstdsig also derives from the
	// same src/std). Because both are computed independently from src/std, a
	// stale stdsig_gen.go is actually caught instead of silently matching.
	if *keyOnly {
		key, err := checker.ComputeStdSigKeyFromFS(fsys)
		if err != nil {
			fatal(fmt.Sprintf("genstdsig: key failed: %v", err))
		}
		fmt.Println(key)
		return
	}

	funcSigs, methodSigs, structFields, aliases, structMod, enumVariants, err := checker.CollectStdSigsFromFS(fsys)
	if err != nil {
		fatal(fmt.Sprintf("genstdsig: collect failed: %v", err))
	}
	key, err := checker.ComputeStdSigKeyFromFS(fsys)
	if err != nil {
		fatal(fmt.Sprintf("genstdsig: key failed: %v", err))
	}
	// Module list (9th baked table). Enumerated from the SAME on-disk src/std
	// via the exported ListStdModules, so it is consistent with the key and the
	// other 8 tables — all derive from src/std.
	mods := checker.ListStdModules(fsys)

	// ---- AST blob (Tier 0) ----
	// Bake every std module's serialized Program (gob of parser.CachedProgram;
	// the whole map is gzipped once here) so `no build` deserializes the std
	// AST instead of lexing+parsing src/std on every invocation.
	// map[embedPath][]byte is gob's natural form; the binary is gzipped to keep
	// the embedded size down.
	astMap, err := checker.SerializeStdAST(fsys)
	if err != nil {
		fatal(fmt.Sprintf("genstdsig: std AST serialize failed: %v", err))
	}
	var astRaw bytes.Buffer
	azw := gzip.NewWriter(&astRaw)
	if err := gob.NewEncoder(azw).Encode(astMap); err != nil {
		fatal(fmt.Sprintf("genstdsig: std AST encode failed: %v", err))
	}
	if err := azw.Close(); err != nil {
		fatal(fmt.Sprintf("genstdsig: std AST gzip failed: %v", err))
	}
	astBinPath := filepath.Join(srcDir, "checker", "stdastembed", "std_ast.bin")
	if err := os.MkdirAll(filepath.Dir(astBinPath), 0o755); err != nil {
		fatal(fmt.Sprintf("genstdsig: mkdir %s: %v", filepath.Dir(astBinPath), err))
	}
	if existing, rerr := os.ReadFile(astBinPath); rerr != nil || !bytes.Equal(existing, astRaw.Bytes()) {
		if err := os.WriteFile(astBinPath, astRaw.Bytes(), 0o644); err != nil {
			fatal(fmt.Sprintf("genstdsig: write %s: %v", astBinPath, err))
		}
	}

	// stdastembed/key.go: carry the same key for staleness detection
	// (StdASTFor falls back to parsing on mismatch). The blob itself is
	// embedded by stdastembed/embed.go via //go:embed std_ast.bin.
	var gbuf bytes.Buffer
	gbuf.WriteString("// Code generated by genstdsig. DO NOT EDIT.\n")
	gbuf.WriteString("// Carries the std-content key so checker can detect a stale\n")
	gbuf.WriteString("// std AST blob. Regenerate via 'go generate ./checker/' (or 'make gen').\n\n")
	gbuf.WriteString("package stdastembed\n\n")
	fmt.Fprintf(&gbuf, "var Key = %s\n", strconv.Quote(key))
	embAstPath := filepath.Join(srcDir, "checker", "stdastembed", "key.go")
	if existing, rerr := os.ReadFile(embAstPath); rerr != nil || !bytes.Equal(existing, gbuf.Bytes()) {
		if err := os.WriteFile(embAstPath, gbuf.Bytes(), 0o644); err != nil {
			fatal(fmt.Sprintf("genstdsig: write %s: %v", embAstPath, err))
		}
	}

	var buf bytes.Buffer
	buf.WriteString(header)
	buf.WriteString("func init() {\n")
	fmt.Fprintf(&buf, "\tembeddedStdSigKey = %s\n", strconv.Quote(key))
	buf.WriteString("\tembeddedStdFuncSigs = ")
	writeMapStringSigInline(&buf, funcSigs)
	buf.WriteString("\tembeddedStdMethodSigs = ")
	writeMapStringSigInline(&buf, methodSigs)
	buf.WriteString("\tembeddedStdStructFields = ")
	writeMapStringMapInline(&buf, structFields)
	buf.WriteString("\tembeddedStdAliases = ")
	writeMapStringInline(&buf, aliases)
	buf.WriteString("\tembeddedStdStructMod = ")
	writeMapStringInline(&buf, structMod)
	buf.WriteString("\tembeddedStdEnumVariants = ")
	writeMapStringSliceInline(&buf, enumVariants)
	buf.WriteString("\tembeddedStdModules = ")
	writeModuleInfos(&buf, mods)
	buf.WriteString("}\n")

	formatted, err := goformat.Source(buf.Bytes())
	if err != nil {
		fatal(fmt.Sprintf("genstdsig: gofmt failed: %v\n---\n%s", err, buf.String()))
	}

	outPath := filepath.Join(genDir, "..", "stdsig_gen.go")
	// Preserve mtime when unchanged so incremental `make no` does not rebuild
	// the binary on every run.
	if existing, rerr := os.ReadFile(outPath); rerr == nil && bytes.Equal(existing, formatted) {
		return
	}
	if err := os.WriteFile(outPath, formatted, 0o644); err != nil {
		fatal(fmt.Sprintf("genstdsig: write %s: %v", outPath, err))
	}
	fmt.Printf("genstdsig: wrote %s (%d func sigs (params+results), %d method sigs (params+results), %d structs, %d aliases, %d enumTypes)\n",
		outPath, len(funcSigs), len(methodSigs), len(structFields), len(aliases), len(enumVariants))
}

func writeMapStringSliceInline(buf *bytes.Buffer, m map[string][]string) {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)

	if len(keys) == 0 {
		buf.WriteString("map[string][]string{}\n")
		return
	}
	buf.WriteString("map[string][]string{\n")
	for _, k := range keys {
		vals := m[k]
		fmt.Fprintf(buf, "\t%s: {", strconv.Quote(k))
		for i, v := range vals {
			if i > 0 {
				buf.WriteString(", ")
			}
			buf.WriteString(strconv.Quote(v))
		}
		buf.WriteString("},\n")
	}
	buf.WriteString("}\n")
}

// writeMapStringSigInline writes a map[string]checker.StdSigEntry literal. Each
// value carries both its PARAMETER types (Params) and RESULT types (Results),
// merging the old *Sigs + *Params tables into one entry — see stdsig_cache.go.
func writeMapStringSigInline(buf *bytes.Buffer, m map[string]checker.StdSigEntry) {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)

	if len(keys) == 0 {
		buf.WriteString("map[string]StdSigEntry{}\n")
		return
	}
	buf.WriteString("map[string]StdSigEntry{\n")
	for _, k := range keys {
		e := m[k]
		fmt.Fprintf(buf, "\t%s: StdSigEntry{Params: []string{", strconv.Quote(k))
		for i, v := range e.Params {
			if i > 0 {
				buf.WriteString(", ")
			}
			buf.WriteString(strconv.Quote(v))
		}
		buf.WriteString("}, Results: []string{")
		for i, v := range e.Results {
			if i > 0 {
				buf.WriteString(", ")
			}
			buf.WriteString(strconv.Quote(v))
		}
		buf.WriteString("}},\n")
	}
	buf.WriteString("}\n")
}

func writeMapStringMapInline(buf *bytes.Buffer, m map[string]map[string]string) {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)

	if len(keys) == 0 {
		buf.WriteString("map[string]map[string]string{}\n")
		return
	}
	buf.WriteString("map[string]map[string]string{\n")
	for _, outer := range keys {
		inner := m[outer]
		ikeys := make([]string, 0, len(inner))
		for ik := range inner {
			ikeys = append(ikeys, ik)
		}
		sort.Strings(ikeys)

		fmt.Fprintf(buf, "\t%s: {\n", strconv.Quote(outer))
		for _, ik := range ikeys {
			fmt.Fprintf(buf, "\t\t%s: %s,\n", strconv.Quote(ik), strconv.Quote(inner[ik]))
		}
		buf.WriteString("\t},\n")
	}
	buf.WriteString("}\n")
}

// writeModuleInfos emits the std module list as a compact KV map literal
// (ShortName -> FullPath) instead of a []StdModuleInfo slice. ShortName is
// unique across std modules; a collision would silently drop a module from the
// baked table, so we fail loudly instead of losing data.
func writeModuleInfos(buf *bytes.Buffer, mods []checker.StdModuleInfo) {
	m := make(map[string]string, len(mods))
	for _, mod := range mods {
		if prev, dup := m[mod.ShortName]; dup && prev != mod.FullPath {
			fatal(fmt.Sprintf("genstdsig: duplicate std module ShortName %q (FullPath %q vs %q)", mod.ShortName, prev, mod.FullPath))
		}
		m[mod.ShortName] = mod.FullPath
	}
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)

	if len(keys) == 0 {
		buf.WriteString("map[string]string{}\n")
		return
	}
	buf.WriteString("map[string]string{\n")
	for _, k := range keys {
		fmt.Fprintf(buf, "\t%s: %s,\n", strconv.Quote(k), strconv.Quote(m[k]))
	}
	buf.WriteString("}\n")
}

